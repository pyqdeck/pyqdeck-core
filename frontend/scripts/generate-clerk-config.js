#!/usr/bin/env node
/**
 * Regenerates src/lib/clerk-auth-config.json from Clerk's public
 * /v1/environment endpoint (the same one Clerk's own components read) so
 * the custom sign-in/sign-up forms can render the right fields and OAuth
 * buttons synchronously, no runtime fetch or loading spinner.
 *
 * Run this after changing anything in the Clerk Dashboard that affects the
 * sign-in/sign-up forms (enabling/disabling a field, connecting a new OAuth
 * provider, etc.) and whenever NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY changes
 * (e.g. switching between a test and live instance):
 *
 *   pnpm sync:clerk-config
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT_FILE = path.join(ROOT, 'src', 'lib', 'clerk-auth-config.json');

function readPublishableKey() {
  if (process.env.NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY) {
    return process.env.NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY;
  }
  const envPath = path.join(ROOT, '.env.local');
  const contents = fs.readFileSync(envPath, 'utf8');
  const match = contents.match(/^NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY=(.+)$/m);
  if (!match) {
    throw new Error(
      `NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY not found in ${envPath} or the environment`
    );
  }
  return match[1].trim();
}

function frontendApiOrigin(publishableKey) {
  const encoded = publishableKey.replace(/^pk_(test|live)_/, '');
  const host = Buffer.from(encoded, 'base64')
    .toString('utf8')
    .replace(/\$$/, '');
  if (!host)
    throw new Error(`Could not decode publishable key: ${publishableKey}`);
  return `https://${host}`;
}

async function main() {
  const publishableKey = readPublishableKey();
  const origin = frontendApiOrigin(publishableKey);

  console.log(`Fetching Clerk environment config from ${origin} ...`);
  const res = await fetch(`${origin}/v1/environment`);
  if (!res.ok) {
    throw new Error(
      `Clerk environment fetch failed: ${res.status} ${res.statusText}`
    );
  }
  const data = await res.json();

  const social = data?.user_settings?.social || {};
  const attributes = data?.user_settings?.attributes || {};

  const config = {
    _meta: {
      generatedAt: new Date().toISOString(),
      source: `${origin}/v1/environment`,
      note: 'Generated by scripts/generate-clerk-config.js -- do not hand-edit, run `pnpm sync:clerk-config` instead.',
    },
    socialProviders: Object.entries(social)
      .filter(([, cfg]) => cfg?.enabled)
      .map(([strategy, cfg]) => ({
        strategy,
        name: cfg.name || strategy,
        logoUrl: cfg.logo_url,
      })),
    attributes: Object.fromEntries(
      Object.entries(attributes).map(([key, cfg]) => [
        key,
        { enabled: !!cfg?.enabled, required: !!cfg?.required },
      ])
    ),
  };

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, JSON.stringify(config, null, 2) + '\n');
  console.log(`Wrote ${path.relative(ROOT, OUT_FILE)}`);
  console.log(
    `  Social providers: ${config.socialProviders.map((p) => p.name).join(', ') || 'none'}`
  );
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
